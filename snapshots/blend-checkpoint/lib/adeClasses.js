export function labelGroup(label) {
  if (FURNITURE_LABELS.has(label)) return "furniture"
  if (SCENE_LABELS.has(label)) return "scene"
  return "other"
}

export function allowedLabelsForSeed(seedLabel) {
  const group = labelGroup(seedLabel)
  if (group === "furniture") return FURNITURE_LABELS
  if (group === "scene") return new Set([seedLabel])
  return seedLabel ? new Set([seedLabel]) : null
}

export function labelInKorean(label) {
  return LABEL_KO[label] || label
}
